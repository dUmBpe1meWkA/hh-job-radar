from __future__ import annotations

from scoring import category


def make_letter(vacancy: dict) -> str:
    company = (vacancy.get("employer") or {}).get("name") or "вашей компании"
    cat = category(vacancy)

    base_intro = (
        "Здравствуйте!\n\n"
        "Меня зовут Алексей, я студент МТУСИ по направлению «Безопасность компьютерных систем». "
        "Ищу стажировку или junior-позицию и хочу развиваться в информационной безопасности.\n\n"
    )

    if cat == "soc":
        body = (
            f"Меня заинтересовала вакансия в {company}, потому что хочу развиваться в SOC, мониторинге ИБ "
            "и анализе событий безопасности. Есть базовое понимание Linux, TCP/IP, DNS, HTTP/HTTPS, SSH, "
            "серверной инфраструктуры и Python-автоматизации. Участвовал в CTF и самостоятельно изучаю прикладную ИБ.\n\n"
            "В pet-проектах работал с Linux/VPS, Cloudflare, DNS, FastAPI, Git, базовой настройкой серверной среды "
            "и автоматизацией задач. Готов учиться, работать с логами, следовать регламентам и быстро погружаться "
            "в инструменты команды."
        )
    elif cat == "infra":
        body = (
            f"Меня заинтересовала вакансия в {company}, потому что мне близки задачи Linux-инфраструктуры, "
            "сетевых сервисов и базовой защиты серверной среды. Есть практический опыт с Linux/VPS, SSH, DNS, "
            "Cloudflare, Docker Compose, Git, Python/Bash и деплоем pet-проектов.\n\n"
            "Из проектов: социальная платформа на FastAPI/React, сайт-портфолио, Linux-тренажёр, автоматизация "
            "серверных задач, VPN-клиент и Firefox-расширение. Готов быстро учиться и брать технические задачи."
        )
    elif cat == "dev":
        body = (
            f"Меня заинтересовала вакансия в {company}, потому что хочу развиваться на стыке разработки и ИБ. "
            "Есть опыт pet-проектов на Python/FastAPI, REST API, Pydantic, React/JavaScript, Linux/VPS, Cloudflare, "
            "Git и Docker Compose.\n\n"
            "Коммерческого опыта пока нет, но я умею доводить проекты до рабочего состояния: запускать, тестировать, "
            "деплоить, разбирать ошибки и дорабатывать результат. Готов выполнить тестовое задание."
        )
    else:
        body = (
            f"Меня заинтересовала вакансия в {company}, потому что хочу развиваться в прикладной информационной "
            "безопасности. Есть база по Linux, сетям, DNS, HTTP/HTTPS, SSH, Python, Git и настройке серверной среды.\n\n"
            "В pet-проектах работал с Linux/VPS, Cloudflare, FastAPI, REST API, базовой защитой серверов и автоматизацией. "
            "Готов быстро учиться, работать с документацией и выполнить тестовое задание."
        )

    return base_intro + body
